"""Build the project database from scratch.

Run from the project root:
    python src/build_db.py

Deletes and rebuilds data/netaporter.duckdb by running sql/01-03 in
order, writes notes/cleaning_log.md, then prints the checks in
sql/04_checks.sql. Safe to rerun any time you change a decision.
"""
from pathlib import Path

import duckdb
import pandas as pd

DB = Path("data/netaporter.duckdb")
BUILD_FILES = ["sql/01_load_raw.sql", "sql/02_clean.sql", "sql/03_build_tables.sql"]
CHECKS_FILE = Path("sql/04_checks.sql")
LOG_FILE = Path("notes/cleaning_log.md")

# 1. Start fresh
if DB.exists():
    DB.unlink()
con = duckdb.connect(str(DB))

# 2. Run the build files in order
for path in BUILD_FILES:
    print(f"Running {path}")
    con.execute(Path(path).read_text())

# 3. Write the cleaning log as a Markdown table
def fmt(value):
    return "" if pd.isna(value) else f"{int(value):,}"

log = con.sql("SELECT * FROM cleaning_log ORDER BY step_no").df()
lines = [
    "# Cleaning log",
    "",
    "Generated by `src/build_db.py`. Rebuild instead of editing by hand.",
    "",
    "| Step | What | Rows before | Rows after | Rows affected | Why |",
    "|---|---|---|---|---|---|",
]
for row in log.itertuples():
    lines.append(
        f"| {row.step_no} | {row.step} | {fmt(row.rows_before)} | "
        f"{fmt(row.rows_after)} | {fmt(row.rows_affected)} | {row.reason} |"
    )
LOG_FILE.write_text("\n".join(lines) + "\n")
print(f"Wrote {LOG_FILE}\n")
print(log.to_string(index=False))

# 4. Run and print each check
for block in CHECKS_FILE.read_text().split("-- check:")[1:]:
    title, _, sql = block.partition("\n")
    print(f"\n=== {title.strip()} ===")
    result = con.sql(sql).df()
    print("(none)" if result.empty else result.to_string(index=False))

con.close()
